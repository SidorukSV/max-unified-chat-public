param([string]$ExtensionPath = (Join-Path $PSScriptRoot '../src/extension/бит_МедицинаОмни_ПРОФ'))

# Emits a BSL test for execute_code in an isolated test infobase.
# Uses the actual form query/grouping implementation, not a duplicate algorithm.
$sourcePath = Join-Path $ExtensionPath 'DataProcessors/бит_омни_ЕдиныйЧат/Forms/Форма/Ext/Form/Module.bsl'
$source = Get-Content -Raw -Encoding UTF8 -LiteralPath $sourcePath
$body = [regex]::Match($source, '(?s)Функция СвернутыеДиалогиНаСервере\(\)(.*?)КонецФункции').Groups[1].Value
if (-not $body.Contains('Возврат СвернутыеДиалоги;')) { throw 'Form implementation not found' }
$body = $body.Replace('Возврат СвернутыеДиалоги;', '')
$before = @'
НачатьТранзакцию();
Попытка
    Запрос = Новый Запрос("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.бит_омни_Боты ГДЕ НЕ ПометкаУдаления");
    Боты = Запрос.Выполнить().Выгрузить();
    Запрос = Новый Запрос("ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ Справочник.Клиенты ГДЕ НЕ ПометкаУдаления И НЕ ЭтоГруппа");
    Пациенты = Запрос.Выполнить().Выгрузить();
    Если Боты.Количество() = 0 Или Пациенты.Количество() = 0 Тогда
        ВызватьИсключение "Test requires one bot and one existing patient";
    КонецЕсли;
    ТестБот = Боты[0].Ссылка;
    ТестПациент = Пациенты[0].Ссылка;
    СтрокаПоиска = "TEST_" + Лев(Строка(Новый УникальныйИдентификатор), 12);
    ТестКонтакты = Новый Массив;
    Для Номер = 1 По 4 Цикл
        Контакт = Справочники.бит_омни_Контакты.СоздатьЭлемент();
        Контакт.Наименование = СтрокаПоиска;
        Контакт.Канал = Перечисления.бит_омни_КаналыСвязи.MAX;
        Контакт.Бот = ТестБот;
        Контакт.Идентификатор = 990000000000 + Номер;
        Если Номер > 2 Тогда
            Контакт.Получатель = ТестПациент;
        КонецЕсли;
        Контакт.ОбменДанными.Загрузка = Истина;
        Контакт.ДополнительныеСвойства.Вставить("НеРегистрироватьДляОбмена", Истина);
        Контакт.Записать();
        ТестКонтакты.Добавить(Контакт.Ссылка);
        История = РегистрыСведений.бит_омни_ИсторияЧатовMAX.СоздатьМенеджерЗаписи();
        История.Период = ТекущаяДатаСеанса();
        История.ИдентификаторСообщения = Строка(Новый УникальныйИдентификатор);
        История.Контакт = Контакт.Ссылка;
        История.Бот = ТестБот;
        История.Входящее = Истина;
        История.Прочитано = Ложь;
        История.Текст = "test incoming " + Номер;
        История.Записать();
    КонецЦикла;
'@
$after = @'
    Если СвернутыеДиалоги.Количество() <> 3 Тогда
        ВызватьИсключение "Expected two independent contacts and one grouped patient dialog";
    КонецЕсли;
    Для Каждого Диалог Из СвернутыеДиалоги Цикл
        Ожидалось = ?(ЗначениеЗаполнено(Диалог.Пациент), 2, 1);
        Если Диалог.Непрочитано <> Ожидалось Тогда
            ВызватьИсключение "Unread counters mixed between contacts";
        КонецЕсли;
        Если Не ЗначениеЗаполнено(Диалог.ДатаПоследнегоВходящего) Тогда
            ВызватьИсключение "Missing incoming notification date";
        КонецЕсли;
    КонецЦикла;
    Для Номер = 0 По 1 Цикл
        Состояние = РегистрыСведений.бит_омни_СостоянияДиалоговMAX.СоздатьМенеджерЗаписи();
        Состояние.Пациент = ТестКонтакты[Номер];
        Состояние.Бот = ТестБот;
        Состояние.Состояние = ?(Номер = 0,
            Перечисления.бит_омни_СостоянияДиалоговMAX.ВРаботе,
            Перечисления.бит_омни_СостоянияДиалоговMAX.Закрыт);
        Состояние.Записать();
    КонецЦикла;
    Для Номер = 0 По 1 Цикл
        Состояние = РегистрыСведений.бит_омни_СостоянияДиалоговMAX.СоздатьМенеджерЗаписи();
        Состояние.Пациент = ТестКонтакты[Номер];
        Состояние.Бот = ТестБот;
        Состояние.Прочитать();
        Ожидалось = ?(Номер = 0,
            Перечисления.бит_омни_СостоянияДиалоговMAX.ВРаботе,
            Перечисления.бит_омни_СостоянияДиалоговMAX.Закрыт);
        Если Состояние.Состояние <> Ожидалось Тогда
            ВызватьИсключение "Contact states are not independent";
        КонецЕсли;
    КонецЦикла;
    Результат = "PASS: unlinked isolation, linked grouping, unread counts, incoming dates, independent states; rolled back";
    ОтменитьТранзакцию();
Исключение
    ОтменитьТранзакцию();
    ВызватьИсключение;
КонецПопытки;
'@
($before + "`n" + $body + "`n" + $after) | ConvertTo-Json -Compress
